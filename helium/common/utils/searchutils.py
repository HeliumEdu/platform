_WHITESPACE = re.compile(r'\s+')
_TOKEN_EDGE_PUNCT = re.compile(r'^[^a-z0-9]+|[^a-z0-9]+$')
_COMBINING_DIACRITICAL_MARKS = range(0x0300, 0x0370)


def normalize_search_text(text: str) -> str:
    """
    Lowercase and fold diacritics, e.g. ``'Café'`` -> ``'cafe'``, using the same replacement
    table as the frontend's `diacritic` package.

    :param text: The query or haystack text.
    :return: The normalized text.
    """
    return ''.join(_fold_code_unit(ord(char)) for char in text.lower())


def _fold_code_unit(unit: int) -> str:
    if unit in _COMBINING_DIACRITICAL_MARKS:
        return ''
    if unit in _SINGLE_UNIT:
        return chr(_SINGLE_UNIT[unit])
    return _MULTI_UNIT.get(unit, chr(unit))


def tokenize_search_query(query: str) -> List[str]:
    """
    Split a query into normalized, whitespace-delimited terms with stray leading/trailing punctuation
    removed (``'weekend.'`` -> ``'weekend'``); internal punctuation is kept so ``'p.42-50'`` still matches
    exactly. Quotes carry no phrase meaning.

    :param query: The raw ``?search=`` value.
    :return: The terms; empty when the query is blank.
    """
    trimmed = query.strip()
    if not trimmed:
        return []
    tokens = (_TOKEN_EDGE_PUNCT.sub('', token) for token in _WHITESPACE.split(normalize_search_text(trimmed)))
    return [token for token in tokens if token]


def matches_search_terms(haystacks: Iterable[str], terms: Iterable[str]) -> bool:
    """
    True when every term appears in at least one haystack. Haystacks are normalized here; terms must
    already come from :func:`tokenize_search_query`.

    :param haystacks: The raw field values to search.
    :param terms: The normalized query terms.
    :return: Whether the row matches.
    """
    normalized_haystacks = [normalize_search_text(haystack) for haystack in haystacks if haystack]
    return all(any(term in haystack for haystack in normalized_haystacks) for term in terms)
